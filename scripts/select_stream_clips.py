"""Write ordered frame lists for the ROD video clips used by `vision_assist.stream`.

About 3% of ROD images are frames Roboflow extracted from videos. Their original
names, kept in the dataset's rename_map.csv, end in "<video>_mp4-<frame>_jpg".
This collects one video's frames in frame order. The frames are spread across
train/valid/test, so the model has seen some of them: these clips test alert
timing, not detection accuracy.

Usage:
    python scripts/select_stream_clips.py /path/to/ROD-Dataset/dataset
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CLIPS = {
    "stream_people_clip.txt": (
        "-BfPbDb0lSK4-_mp4",
        "Street vlog: two people in view almost throughout. 119 consecutive frames (0-118), no gaps.",
    ),
    "stream_dashcam_clip.txt": (
        "training-AI-CROPPED_mp4",
        "Dashcam drive: the 135 frames kept in ROD out of frames 9-994, so there are jumps of up to "
        "139 frames. Treat it as a jumpy, sub-sampled feed.",
    ),
}


def main(dataset_root: str) -> None:
    root = Path(dataset_root)
    rows = list(csv.DictReader((root / "rename_map.csv").open()))
    for list_name, (video, description) in CLIPS.items():
        frames: dict[int, tuple[str, str]] = {}
        for row in rows:
            m = re.fullmatch(re.escape(video) + r"-(\d+)_jpg\.rf\.[0-9a-f]+", row["old_stem"])
            if m:  # keep the first copy of each frame (sorted by split, then name) for determinism
                entry = (row["split"], f"{row['split']}/images/{row['new_stem']}{row['image_ext']}")
                frames[int(m[1])] = min(frames.get(int(m[1]), entry), entry)
        if not frames:
            raise SystemExit(f"No frames found for {video} in {root / 'rename_map.csv'}")
        lines = [
            f"# {description}",
            f"# Source video in ROD's rename_map.csv: {video}. Generated by scripts/select_stream_clips.py.",
            "# Paths are relative to ROD-Dataset/dataset. Format: path  # source frame number (split)",
        ]
        lines += [f"{path}  # frame {n} ({split})" for n, (split, path) in sorted(frames.items())]
        out = REPO / "configs" / list_name
        out.write_text("\n".join(lines) + "\n")
        print(f"{out.relative_to(REPO)}: {len(frames)} frames")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
