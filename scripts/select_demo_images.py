"""Choose the demo images from ROD *ground-truth labels* (never model predictions).

Deterministic rule, validation split only (the test split stays reserved for scoring):
1. Up to 6 "multi-hazard" images: >= 2 alert-worthy classes, at least one HIGH tier.
   Picked greedily to cover the most not-yet-covered classes; ties -> more classes,
   then file name.
2. One image containing Stairs and one containing Manhole (most alert-worthy classes,
   then file name), so the two main trip hazards appear.

Usage:
    python scripts/select_demo_images.py --dataset /path/to/ROD-Dataset/dataset
writes configs/demo_images.txt
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from vision_assist.guidance import HAZARD_TIERS, HIGH  # noqa: E402

CLASS_NAMES = yaml.safe_load((REPO / "configs" / "rod_detection.yaml").read_text())["names"]


def alertable_classes(label: Path) -> set[str]:
    classes = {CLASS_NAMES[int(line.split()[0])] for line in label.read_text().splitlines() if line.strip()}
    return {c for c in classes if c in HAZARD_TIERS}


def select(split_dir: Path, n_multi: int = 6) -> list[tuple[str, list[str]]]:
    labelled = {}
    for img in sorted((split_dir / "images").iterdir()):
        label = split_dir / "labels" / f"{img.stem}.txt"
        if label.is_file():
            labelled[img.name] = alertable_classes(label)

    multi = {
        name: cls for name, cls in labelled.items()
        if len(cls) >= 2 and any(HAZARD_TIERS[c] == HIGH for c in cls)
    }
    chosen, covered = [], set()
    while multi and len(chosen) < n_multi:
        name = min(multi, key=lambda n: (-len(multi[n] - covered), -len(multi[n]), n))
        covered |= multi[name]
        chosen.append((name, sorted(multi.pop(name))))

    taken = {name for name, _ in chosen}
    for hazard in ("Stairs", "Manhole"):
        options = [n for n, cls in labelled.items() if hazard in cls and n not in taken]
        if options:
            name = min(options, key=lambda n: (-len(labelled[n]), n))
            chosen.append((name, sorted(labelled[name])))
            taken.add(name)
    return chosen


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dataset", required=True, help="ROD-Dataset/dataset directory")
    p.add_argument("--out", default=str(REPO / "configs" / "demo_images.txt"))
    args = p.parse_args()

    chosen = select(Path(args.dataset) / "valid")
    lines = [
        "# ROD validation images used by the demo, in playback order.",
        "# Generated by scripts/select_demo_images.py from ground-truth labels only.",
        "# Format: file name  # ground-truth alert-worthy classes",
    ]
    lines += [f"{name}  # {', '.join(cls)}" for name, cls in chosen]
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
