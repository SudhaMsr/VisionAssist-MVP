"""Re-split ROD so no original photo or video appears in two splits.

ROD's own train/valid/test splits share sources: Roboflow exported several copies of
one original photo, and frames of one video landed in different splits. About 21% of
validation and test images share a source with training, which inflates scores.

This groups images by source (the original file name before Roboflow's ".rf." suffix,
or the whole video for "<video>_mp4-<frame>" frames), shuffles the groups with a fixed
seed and fills test, then validation, to about 10% of images each; the rest is training.

Usage:
    python -m training.splits --dataset /path/to/ROD-Dataset/dataset
Writes configs/finetune_v1/splits/rod_{train,val,test}.txt (paths relative to the
dataset folder) and rod_split_report.json. Re-running with the same data gives the
same lists.
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import re
from collections import Counter, defaultdict
from pathlib import Path

from training.common import CLASS_NAMES, SEED, SPLIT_DIR, read_yolo_labels

VIDEO_FRAME = re.compile(r"(.*_mp4)-\d+_jpg$")


def source_group(old_stem: str) -> str:
    stem = old_stem.split(".rf.")[0]
    m = VIDEO_FRAME.match(stem)
    return m.group(1) if m else stem


def group_images(rename_rows: list[dict]) -> dict[str, list[str]]:
    """Source group -> sorted image paths ('<split>/images/<new_stem><ext>')."""
    groups: dict[str, list[str]] = defaultdict(list)
    for row in rename_rows:
        groups[source_group(row["old_stem"])].append(f"{row['split']}/images/{row['new_stem']}{row['image_ext']}")
    return {g: sorted(v) for g, v in groups.items()}


def assign(groups: dict[str, list[str]], test_frac: float = 0.10, val_frac: float = 0.10,
           seed: int = SEED) -> dict[str, list[str]]:
    if not 0 < test_frac + val_frac < 1:
        raise ValueError(f"test_frac + val_frac must be in (0, 1), got {test_frac + val_frac}")
    keys = sorted(groups)
    random.Random(seed).shuffle(keys)
    total = sum(len(v) for v in groups.values())
    out = {"test": [], "val": [], "train": []}
    for key in keys:
        target = ("test" if len(out["test"]) < test_frac * total
                  else "val" if len(out["val"]) < val_frac * total else "train")
        out[target].extend(groups[key])
    return {k: sorted(v) for k, v in out.items()}


def class_counts(dataset: Path, images: list[str]) -> dict[str, int]:
    counts = Counter()
    for rel in images:
        split, _, name = rel.split("/")
        for row in read_yolo_labels(dataset / split / "labels" / (Path(name).stem + ".txt")):
            counts[CLASS_NAMES[row[0]]] += 1
    return {c: counts.get(c, 0) for c in CLASS_NAMES}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dataset", required=True, help="ROD-Dataset/dataset folder (contains rename_map.csv)")
    p.add_argument("--out", default=str(SPLIT_DIR))
    p.add_argument("--seed", type=int, default=SEED)
    args = p.parse_args(argv)
    dataset, out = Path(args.dataset), Path(args.out)

    rows = list(csv.DictReader((dataset / "rename_map.csv").open()))
    groups = group_images(rows)
    splits = assign(groups, seed=args.seed)

    group_of = {img: g for g, imgs in groups.items() for img in imgs}
    shared = {s: {group_of[i] for i in imgs} for s, imgs in splits.items()}
    leaks = {f"{a}&{b}": len(shared[a] & shared[b]) for a, b in (("train", "val"), ("train", "test"), ("val", "test"))}
    if any(leaks.values()):
        raise RuntimeError(f"Source groups shared between splits: {leaks}")

    out.mkdir(parents=True, exist_ok=True)
    header = (f"# ROD re-split by source group (seed {args.seed}); generated by training/splits.py.\n"
              "# Paths are relative to ROD-Dataset/dataset.\n")
    for name, imgs in splits.items():
        (out / f"rod_{name}.txt").write_text(header + "\n".join(imgs) + "\n")
    report = {
        "seed": args.seed,
        "groups": len(groups),
        "images": {k: len(v) for k, v in splits.items()},
        "shared_groups_between_splits": leaks,
        "class_counts": {k: class_counts(dataset, v) for k, v in splits.items()},
    }
    (out / "rod_split_report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: report[k] for k in ("groups", "images", "shared_groups_between_splits")}, indent=2))
    thin = {c: n for c, n in report["class_counts"]["test"].items() if n < 20}
    if thin:
        print(f"Warning: fewer than 20 test boxes for {thin}; per-class scores for these are noisy.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
